// (v11) Autant de carrières et de mines que de gisements libres : placement, places additionnées, travail sur les gisements équipés, sauvegarde.
import { Simulation } from '../src/sim/simulation.js';
import { serialize, restore } from '../src/sim/save.js';
import { TASKS, START_DEPOSITS } from '../src/content/medieval.js';
const ok = (c, m) => { if (!c) { console.log('ÉCHEC :', m); process.exitCode = 1; } else console.log('ok  :', m); };
const sim = new Simulation(), E = sim.eco, B = sim.build;
const run = s => { for (let i = 0; i < s * 20; i++) { if (sim.phase === 'prep') sim.timer = Math.max(sim.timer, 5); sim.tick(); } };
Object.assign(E.res, { wood: 5000, stone: 5000, iron: 500, gold: 500, food: 2000 });
for (let i = 0; i < 10; i++) { E.addVillager(); } E.syncTasks();
const stone = [TASKS.stone.site, ...START_DEPOSITS.stone], iron = [TASKS.iron.site, ...START_DEPOSITS.iron], gold = [TASKS.gold.site, ...START_DEPOSITS.gold];
ok(!B.canPlace('quarry', 100, 240, 0).ok, 'carrière refusée hors gisement de pierre');
ok(!B.canPlace('quarry', iron[0].x, iron[0].z, 0).ok, 'carrière refusée sur le fer');
const q1 = sim.place('quarry', stone[0].x, stone[0].z, 0, 2), q2 = sim.place('quarry', stone[1].x, stone[1].z, 0, 2);
ok(q1 && q2, 'deux carrières sur deux gisements de pierre');
ok(!B.canPlace('quarry', stone[0].x, stone[0].z, 0).ok, 'gisement déjà exploité : refusé');
ok(!B.canBuildType('quarry').ok, 'plus aucun gisement de pierre libre : construction impossible (' + B.canBuildType('quarry').why + ')');
const mines = [...iron, ...gold].map(o => sim.place('mine', o.x, o.z, 0, 2));
ok(mines.every(Boolean), `${mines.length} mines sur tous les gisements de fer et d'or`);
ok(B.newCost('mine').wood > 100, 'chaque mine de plus coûte davantage : ' + JSON.stringify(B.newCost('mine')));
run(260);
ok([q1, q2, ...mines].every(s => s.state === 'built'), 'toutes construites');
ok(E.slots('quarry') === 3 + 5 * 2, 'places de carriers additionnées : ' + E.slots('quarry'));
ok(E.slots('mine') === 0 + 5 * mines.length, 'places de mineurs additionnées : ' + E.slots('mine'));
E.setAssign('stone', 8); run(30);
const at = new Set(E.villagers.filter(v => v.task === 'stone' && v.sx != null).map(v => `${v.sx},${v.sz}`));
ok(at.size === 2, 'les carriers se répartissent entre les deux carrières : ' + [...at].join(' | '));
ok(sim.upgradeStruct(q2.id), 'amélioration d\'une seule carrière'); run(120);
ok(q2.level === 2 && E.level.quarry === 2 && E.slots('quarry') === 3 + 5 * 3, 'niveau = la meilleure, places = la somme (' + E.slots('quarry') + ')');
E.res.gold = 500; E.res.food = 500; const n0 = E.extra.stone.length;
ok(E.startProspect('stone') && (() => { for (let i = 0; i < 20 * 46; i++) sim.tick(); return E.extra.stone.length === n0 + 1; })(), 'prospection : nouveau gisement de pierre');
ok(B.canBuildType('quarry').ok, 'un gisement découvert permet une carrière de plus');
const snap = JSON.parse(JSON.stringify(serialize(sim))); const s2 = new Simulation(); restore(s2, snap);
ok(s2.build.all('quarry').length === 2 && s2.build.all('mine').length === mines.length && s2.eco.slots('quarry') === E.slots('quarry'), 'sauvegarde/restauration');
